import 'dart:convert';
import 'dart:io';

import 'package:dart_style/dart_style.dart';

void main() {
  final directory = Platform.script.resolve('../lib/src/cli/');
  final source = File.fromUri(directory.resolve('commands.json'))
      .readAsStringSync();
  File.fromUri(directory.resolve('commands.g.dart'))
      .writeAsStringSync(generateCommands(source));
}

String generateCommands(String source) {
  jsonDecode(source);
  final literal = jsonEncode(source).replaceAll(r'$', r'\$');
  return DartFormatter(languageVersion: DartFormatter.latestLanguageVersion)
      .format(
        '// Generated by dart run tool/generate_commands.dart. Do not edit.\n'
        'const embeddedCommandsJson = $literal;\n',
      );
}
